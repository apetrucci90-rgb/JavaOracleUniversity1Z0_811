package variableconstantsandtypes;

public class TipiGiusti {
    public static void main(String[] args) {
        int coperti = 35;
        double prezzoUova = 18.50;
        boolean vegan = false;
        /*
        1. Il tipo è una promessa. Una char contiene sempre esattamente un carattere.
        Con char il compilatore assicura che c'è un'iniziale e basta. è il senso di 
        strongly typed (ogni variabile ha un tipo fisso, deciso quando lo si scrive).
        2. Pesa meno. char è un primitivo (16 bit); String è un oggetto: la variabile
        contiene solo un riferimento ad un oggetto che sta altrove in memoria.
        char si USA quando c'è un carattere solo. 
        */
        char inizialeChef = 'A';
        String nomePiatto = "Uova al Tartufo";


    }
}



