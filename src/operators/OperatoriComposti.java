package operators;

public class OperatoriComposti {
    public static void main(String[] args) {
        
    int totale = 100;

    totale += 20;
    System.out.println(totale);

    totale -= 30;
    System.out.println(totale);

    totale *= 2;
    System.out.println(totale);

    totale /= 3;
    System.out.println(totale);

    totale %= 7;
    System.out.println(totale);
    }

}
